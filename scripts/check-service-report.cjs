const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const vm = require('node:vm');
const moduleResult = { exports: {} };
vm.runInNewContext(ts.transpileModule(fs.readFileSync('src/lib/stream/service-report.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, { exports: moduleResult.exports, module: moduleResult });
const { buildServiceReport } = moduleResult.exports;
const at = (minute) => new Date(Date.UTC(2026, 9, 7, 10, minute)).toISOString();
const service = { roomName: 'test-service', title: 'Test', startedAt: at(0), endedAt: at(60), finalIndividualCount: 800 };
const visit = (id, audienceType = 'individual', options = {}) => ({ id, identity: id, accountUid: id, name: id, audienceType, connectedAt: at(1), disconnectedAt: null, specialAccessCode: null, privateDeveloper: false, ...options });
const sessions = Array.from({ length: 1100 }, (_, index) => visit(`person-${index}`, 'individual', { disconnectedAt: index >= 800 ? at(30) : null, specialAccessCode: index === 0 ? '123456' : null }));
sessions.push(visit('church', 'church'), visit('special-church', 'church', { specialAccessCode: '654321' }), visit('presenter', 'presenter'), visit('private', 'individual', { privateDeveloper: true }), visit('other-tab', 'individual', { accountUid: 'person-0', disconnectedAt: at(20) }));
const report = buildServiceReport(service, sessions);
assert.equal(report.peakIndividuals, 1100);
assert.equal(report.individualsAtEnd, 800);
assert.equal(report.currentIndividuals, 0);
assert.equal(report.sessions.some((s) => s.privateDeveloper), false);
assert.equal(buildServiceReport(service, sessions, true).sessions.some((s) => s.privateDeveloper), true);
const rejoin = buildServiceReport({ ...service, finalIndividualCount: 1 }, [visit('first', 'individual', { accountUid: 'one', disconnectedAt: at(10) }), visit('second', 'individual', { accountUid: 'one', connectedAt: at(15) })]);
assert.equal(rejoin.peakIndividuals, 1);
assert.equal(rejoin.sessions.length, 2);
const live = buildServiceReport({ ...service, endedAt: null, finalIndividualCount: undefined }, sessions);
assert.equal(live.currentIndividuals, 800);
assert.equal(buildServiceReport({ ...service, finalIndividualCount: 1 }, [visit('end', 'individual', { disconnectedAt: at(61) })]).sessions[0].disconnectedAt, null);
console.log('Attendance checks passed: individuals, special access, church exclusion, peak/end totals, privacy, duplicate tabs and reconnects.');
